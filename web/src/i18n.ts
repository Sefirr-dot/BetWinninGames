export function t(key: string): string {
  const e = T[key]
  if (!e) return key
  return e[LANG] || e.en || key
}

/** t() with {0},{1}… placeholders */
export function tf(key: string, ...args: (string | number)[]): string {
  let s = t(key)
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, String(a))
  })
  return s
}

